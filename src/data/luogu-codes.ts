/**
 * 就地给一道题补上洛谷题号（没有映射、或题目自己已经写了题号时不动）。
 * 用于题库分多批构建、来不及走 withLuoguCodes 的场景。
 */
export function withLuoguCode(problem: { id: string; luogu_code?: string }): void {
  const code = BEGINNER_LUOGU_CODES[problem.id];
  if (code && !problem.luogu_code) problem.luogu_code = code;
}

/** 给一个阶段的全部题目补上洛谷题号（返回新对象，不改原数据） */
export function withLuoguCodes<T extends { problems: { id: string; luogu_code?: string }[] }>(
  stage: T,
): T {
  return {
    ...stage,
    problems: stage.problems.map((problem) => {
      const code = BEGINNER_LUOGU_CODES[problem.id];
      return code && !problem.luogu_code ? { ...problem, luogu_code: code } : problem;
    }),
  };
}
